function translateProductName(value: string, locale: Locale): string | undefined {
  if (locale === "en") return value;

  const terms = productNameTerms[locale];
  const words = value.match(/[\p{L}'-]+/gu) ?? [];
  if (words.length === 0 || words.some((word) => !terms[word.toLowerCase()])) return undefined;

  return value.replace(/[\p{L}'-]+/gu, (word) => terms[word.toLowerCase()]);
}

export function translate(value: string, locale: Locale): string {
  const normalized = normalize(value);
  let translated = translations[locale].get(normalized);
  if (!translated) {
    const generatedDescription = value.match(
      /^(.+) prepared fresh to order with carefully selected ingredients\.$/i,
    );
    const action = normalized.match(/^(.+) (added to cart|added to wishlist|removed from wishlist)$/);
    const count = normalized.match(/^(cart|wishlist), (\d+) items?$/);
    const removal = normalized.match(/^remove (.+) from cart$/);
    const quantity = normalized.match(/^quantity for (.+)$/);
    if (generatedDescription && locale !== "en") {
      const productName = translate(generatedDescription[1], locale);
      if (productName !== generatedDescription[1]) {
        translated = locale === "fr"
          ? `${productName} préparé frais à la commande avec des ingrédients soigneusement sélectionnés.`
          : `${productName} يُحضّر طازجًا عند الطلب بمكونات مختارة بعناية.`;
      }
    } else if (action) {
      const item = translate(action[1], locale);
      const suffix = locale === "fr"
        ? action[2] === "added to cart" ? "ajouté au panier" : action[2] === "added to wishlist" ? "ajouté aux favoris" : "retiré des favoris"
        : locale === "ar"
          ? action[2] === "added to cart" ? "أُضيف إلى السلة" : action[2] === "added to wishlist" ? "أُضيف إلى قائمة الرغبات" : "أُزيل من قائمة الرغبات"
          : action[2] === "added to cart" ? "added to cart" : action[2] === "added to wishlist" ? "added to wishlist" : "removed from wishlist";
      translated = `${item} ${suffix}`;
    } else if (count) {
      const label = count[1] === "cart"
        ? locale === "fr" ? "Panier" : locale === "ar" ? "السلة" : "Cart"
        : locale === "fr" ? "Favoris" : locale === "ar" ? "قائمة الرغبات" : "Wishlist";
      translated = locale === "fr"
        ? `${label}, ${count[2]} article${count[2] === "1" ? "" : "s"}`
        : locale === "ar"
          ? `${label}، ${count[2]} عناصر`
          : `${label}, ${count[2]} item${count[2] === "1" ? "" : "s"}`;
    } else if (removal) {
      translated = `${locale === "fr" ? "Retirer" : locale === "ar" ? "إزالة" : "Remove"} ${translate(removal[1], locale)} ${locale === "fr" ? "du panier" : locale === "ar" ? "من السلة" : "from cart"}`;
    } else if (quantity) {
      translated = `${locale === "fr" ? "Quantité pour" : locale === "ar" ? "الكمية لـ" : "Quantity for"} ${translate(quantity[1], locale)}`;
    } else {
      translated = translateProductName(value, locale);
    }
  }
  if (!translated) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}
